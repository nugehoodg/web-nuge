"""Regenerate data.js from ./img, ./videos and projects.json. Run: python tools/manifest.py"""
import json, os, subprocess
from PIL import Image
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
imgs = []
for f in sorted(os.listdir(os.path.join(root, 'img')), key=str.lower):
    if f.lower().endswith(('.webp', '.png', '.jpg', '.jpeg', '.gif')):
        with Image.open(os.path.join(root, 'img', f)) as im:
            imgs.append({'src': 'img/' + f, 'w': im.width, 'h': im.height})
vids = []
for f in sorted(os.listdir(os.path.join(root, 'videos')), key=str.lower):
    if f.lower().endswith(('.webm', '.mp4', '.mov')):
        p = os.path.join(root, 'videos', f)
        try:
            out = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', p], capture_output=True, text=True).stdout
            d = round(float(out.strip()), 2)
        except Exception:
            d = 10
        vids.append({'src': 'videos/' + f, 'name': os.path.splitext(f)[0], 'dur': d})
def probe_size(path):
    out = subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height',
                          '-of', 'csv=p=0', path], capture_output=True, text=True).stdout.strip()
    w, h = out.split(',')[:2]
    return int(w), int(h)

# Graphic Design gallery: exactly what projects.json lists, in its order
projects = []
with open(os.path.join(root, 'projects.json'), encoding='utf-8') as fh:
    for p in json.load(fh):
        src = p.get('image') or p.get('video')
        path = os.path.join(root, src)
        if not os.path.exists(path):
            print('skipping missing', src)
            continue
        if p.get('image'):
            with Image.open(path) as im:
                w, h = im.width, im.height
        else:
            w, h = probe_size(path)
        projects.append({'title': p.get('title', ''), 'tags': p.get('tags', []),
                         'src': src, 'type': 'video' if p.get('video') else 'image', 'w': w, 'h': h})

# Bento projects: portfolio.json groups projects.json entries into projects
by_src = {p['src']: p for p in projects}
portfolio = []
pf = os.path.join(root, 'portfolio.json')
if os.path.exists(pf):
    with open(pf, encoding='utf-8') as fh:
        for prj in json.load(fh)['projects']:
            items = []
            for src in prj['items']:
                if src not in by_src:
                    print('portfolio.json: not in projects.json, skipped:', src)
                    continue
                it = dict(by_src[src])
                base = os.path.splitext(os.path.basename(src))[0]
                if it['type'] == 'video':  # still frame for print / poster
                    it['poster'] = 'img/posters/' + base + '.jpg'
                # print copy: ≤1600px JPEG (first frame for GIFs, poster for videos) keeps the PDF small
                still = os.path.join(root, it['poster'] if it['type'] == 'video' else src)
                pr = os.path.join(root, 'img', 'print', base + '.jpg')
                if os.path.exists(still) and (not os.path.exists(pr) or os.path.getmtime(pr) < os.path.getmtime(still)):
                    os.makedirs(os.path.dirname(pr), exist_ok=True)
                    with Image.open(still) as im:
                        im.seek(0)
                        im = im.convert('RGBA')
                        flat = Image.new('RGB', im.size, (255, 255, 255)); flat.paste(im, mask=im.split()[3])
                        flat.thumbnail((1600, 1600), Image.LANCZOS)
                        flat.save(pr, 'JPEG', quality=84, optimize=True, progressive=True)
                if os.path.exists(pr):
                    it['print'] = 'img/print/' + base + '.jpg'
                items.append(it)
            if items:
                portfolio.append({**{k: prj.get(k, '') for k in ('id', 'title', 'disciplines', 'year', 'role', 'summary')},
                                  'cover': prj.get('cover') if prj.get('cover') in by_src else items[0]['src'], 'items': items})

with open(os.path.join(root, 'data.js'), 'w', encoding='utf-8') as fh:
    fh.write('// Generated by tools/manifest.py\n')
    fh.write('window.DESIGNS = ' + json.dumps(imgs) + ';\n')
    fh.write('window.VIDEOS = ' + json.dumps(vids) + ';\n')
    fh.write('window.PROJECTS = ' + json.dumps(projects) + ';\n')
    fh.write('window.PORTFOLIO = ' + json.dumps(portfolio, ensure_ascii=False) + ';\n')
print(len(imgs), 'images,', len(vids), 'videos,', len(projects), 'designs,', len(portfolio), 'bento projects')
